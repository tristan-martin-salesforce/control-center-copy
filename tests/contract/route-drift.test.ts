/**
 * Route drift: `src/contract/routes.ts` and the generated `app/api/v1/**\/route.ts` files say the same thing.
 *
 *  1. In sync: re-rendering every route file from the table (the logic of scripts/gen-api-routes.ts) gives byte-for-byte
 *     what is on disk, and no route.ts exists that the table does not produce. If this fails, run `npm run gen:routes`.
 *  2. Covered: every route key is named by at least one test (a DataSource call, `handle('<key>')`, `api('<key>')`, or a
 *     contract test), or sits in UNTESTED below with the reason. A new route that nothing exercises fails here, so
 *     "added a route, tested nothing" cannot merge quietly; a route that gains a test must leave the list.
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

import { routes, type RouteKey } from '@/contract/routes';

const ROOT = path.resolve(__dirname, '../..');

/** Mirrors scripts/gen-api-routes.ts (the generator is a script with side effects, so the rendering is repeated here). */
function expectedFiles(): Map<string, string> {
  const byPath = new Map<string, Array<{ method: string; key: RouteKey }>>();
  for (const key of Object.keys(routes) as RouteKey[]) {
    const def = routes[key];
    const list = byPath.get(def.path) ?? [];
    list.push({ method: def.method, key });
    byPath.set(def.path, list);
  }
  const out = new Map<string, string>();
  for (const [p, handlers] of byPath) {
    const rel = path.posix.join('app/api/v1', ...p.split('/').filter(Boolean).map((seg) => (seg.startsWith(':') ? `[${seg.slice(1)}]` : seg)), 'route.ts');
    const lines = [
      '// Generated by scripts/gen-api-routes.ts from src/contract/routes.ts. Do not edit by hand.',
      "import { handle } from '@/server/http';",
      '',
      "export const runtime = 'nodejs';",
      "export const dynamic = 'force-dynamic';",
      '',
      ...[...handlers].sort((a, b) => a.method.localeCompare(b.method)).map((h) => `export const ${h.method} = handle('${h.key}');`),
      '',
    ];
    out.set(rel, lines.join('\n'));
  }
  return out;
}

function walk(dir: string, match: (name: string) => boolean, skip: (name: string) => boolean = () => false, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (skip(name)) continue;
    const abs = path.join(dir, name);
    if (statSync(abs).isDirectory()) walk(abs, match, skip, out);
    else if (match(name)) out.push(abs);
  }
  return out;
}

describe('the route table and the generated route files agree', () => {
  const expected = expectedFiles();
  // `[...unknown]` is the one hand-written route (the JSON 404 for any path the table does not name), not generated.
  const HAND_WRITTEN = new Set(['app/api/v1/[...unknown]/route.ts']);
  const onDisk = walk(path.join(ROOT, 'app/api/v1'), (n) => n === 'route.ts')
    .map((f) => path.relative(ROOT, f).split(path.sep).join('/'))
    .filter((f) => !HAND_WRITTEN.has(f));

  it('every route in the table has its generated file, with the generated content', () => {
    const drift: string[] = [];
    for (const [rel, content] of expected) {
      let actual: string | null = null;
      try {
        actual = readFileSync(path.join(ROOT, rel), 'utf8');
      } catch {
        actual = null;
      }
      if (actual !== content) drift.push(rel);
    }
    expect(drift, 'run `npm run gen:routes`').toEqual([]);
  });

  it('no route file exists that the table does not produce', () => {
    expect(onDisk.filter((f) => !expected.has(f)).sort(), 'delete the file, or add the route to src/contract/routes.ts').toEqual([]);
  });
});

/** Routes no test names yet, each with why. Keep it short: a route leaves this list the day it gains a test. */
const UNTESTED: Partial<Record<RouteKey, string>> = {
  correctOnsiteDay: 'The onsite engine rules are tested (tests/engines-org62/onsite.test.ts); the route itself has no test yet (gap found by this test, 2026-11)',
  markTrip: 'Same as correctOnsiteDay: the engine is tested, the route is not (gap found by this test, 2026-11)',
  getDoctor: 'The doctor checks are tested in tests/ops/doctor*.test.ts; the HTTP route is a thin wrapper with no test yet',
  smokeClaude: 'Spends one real model call (`claude -p`), refused without a configured AI gateway; no fake exists, so the owner runs it by hand on the work machine',
  getReadme: 'Serves the repository README as markdown; read-only, no test yet',
};

describe('every route has a test or a reason', () => {
  const testFiles = [
    ...walk(path.join(ROOT, 'tests'), (n) => /\.(test|spec)\.tsx?$|\.pg\.ts$/.test(n), (n) => n === 'node_modules' || n === 'fixtures'),
    ...walk(path.join(ROOT, 'src'), (n) => /\.test\.tsx?$/.test(n), (n) => n === 'node_modules'),
  ];
  const corpus = testFiles.filter((f) => f !== __filename).map((f) => readFileSync(f, 'utf8')).join('\n');
  const keys = Object.keys(routes) as RouteKey[];
  const named = (key: string) => new RegExp(`(?<![A-Za-z0-9_$])${key}(?![A-Za-z0-9_$])`).test(corpus);

  it('every route key is named by a test, or is in UNTESTED', () => {
    const missing = keys.filter((k) => !named(k) && !(k in UNTESTED));
    expect(missing, 'add a test that calls the route, or list it in UNTESTED with a reason').toEqual([]);
  });

  it('UNTESTED lists only real, still-untested routes, each with a reason', () => {
    for (const [key, why] of Object.entries(UNTESTED)) {
      expect(key in routes, `${key} is not a route`).toBe(true);
      expect(named(key), `${key} now has a test: remove it from UNTESTED`).toBe(false);
      expect(why?.length ?? 0, `${key} needs a reason`).toBeGreaterThan(10);
    }
  });
});
